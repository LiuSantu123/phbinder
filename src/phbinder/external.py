from pathlib import Path
import re, shutil
from .tools import executable, run

class PDB2PQRAdapter:
    """Build and run a PDB2PQR AMBER preparation command."""
    def __init__(self, executable_path=None): self.executable=executable(executable_path,'pdb2pqr')
    def command(self, pdb, pqr, apbs_input=None, ph=6.5):
        if not self.executable: raise RuntimeError('pdb2pqr executable not found')
        cmd=[self.executable,'--ff','AMBER','--keep-chain','--with-ph',str(ph)]
        if apbs_input: cmd += ['--apbs-input',str(apbs_input)]
        return cmd+[str(pdb),str(pqr)]
    def run(self, pdb, pqr, apbs_input=None, ph=6.5, cwd=None):
        return run(self.command(pdb,pqr,apbs_input,ph),cwd=cwd,timeout=900)

class APBSAdapter:
    """Run APBS and parse the common global electrostatic energy line."""
    def __init__(self, executable_path=None): self.executable=executable(executable_path,'apbs')
    def command(self, input_file):
        if not self.executable: raise RuntimeError('apbs executable not found')
        return [self.executable,str(input_file)]
    def run_energy(self, input_file, cwd=None):
        import re
        p=run(self.command(input_file),cwd=cwd,timeout=900)
        text=p.stdout+'\n'+p.stderr
        vals=re.findall(r'(?:Global net ELEC energy|Local net energy \(PE 0\))\s*=\s*([-+0-9.Ee]+)',text)
        return float(vals[-1]) if vals else float('nan')

def apbs_pair(pdb, workdir, pdb2pqr_path=None, apbs_path=None, ph_on=6.5, ph_off=7.4):
    """Prepare and evaluate both pH states, returning comparable energies.

    PDB2PQR owns force-field charges/radii; APBS input is generated by PDB2PQR.
    Installations with a site-specific charge correction can override this helper
    through the adapter classes without changing the ranking code.
    """
    from pathlib import Path
    w=Path(workdir); w.mkdir(parents=True,exist_ok=True)
    p2q=PDB2PQRAdapter(pdb2pqr_path); ap=APBSAdapter(apbs_path); out={}
    for ph in (ph_on,ph_off):
        tag=str(ph).replace('.','p'); pqr=w/f'pH{tag}.pqr'; inp=w/f'pH{tag}.in'
        p2q.run(pdb,pqr,inp,ph,cwd=w)
        out[str(ph)]=ap.run_energy(inp,cwd=w)
    out['delta']=out[str(ph_on)]-out[str(ph_off)]
    return out

class RosettaInterfaceAdapter:
    """Run Rosetta InterfaceAnalyzer with user-supplied binary and flags."""
    def __init__(self, executable_path=None): self.executable=executable(executable_path,'InterfaceAnalyzer.linuxgccrelease')
    def command(self, structure, scorefile, extra=None):
        if not self.executable: raise RuntimeError('Rosetta InterfaceAnalyzer not found')
        return [self.executable,'-s',str(structure),'-out:file:scorefile',str(scorefile)]+list(extra or [])
    def run(self, structure, scorefile, cwd=None, extra=None):
        return run(self.command(structure,scorefile,extra),cwd=cwd,timeout=3600)

class MMPBSAAdapter:
    """Build AmberTools MMPBSA.py command; topology/trajectory setup is caller-owned."""
    def __init__(self, executable_path=None): self.executable=executable(executable_path,'MMPBSA.py')
    def command(self, input_file, complex_topology, output_file, trajectory=None):
        if not self.executable: raise RuntimeError('MMPBSA.py not found')
        cmd=[self.executable,'-O','-i',str(input_file),'-o',str(output_file),'-cp',str(complex_topology)]
        if trajectory: cmd += ['-y',str(trajectory)]
        return cmd
    def run(self, input_file, complex_topology, output_file, trajectory=None, cwd=None):
        return run(self.command(input_file,complex_topology,output_file,trajectory),cwd=cwd,timeout=86400)

PKA=re.compile(r'^\s*(ASP|GLU|HIS|CYS|TYR|LYS|ARG)\s+(\d+)\s+([A-Za-z])\s+([0-9.]+)')
ACID={'ASP','GLU','CYS','TYR'}

def ensure_pdb(structure, out):
    p=Path(structure); out=Path(out)
    if p.suffix.lower()=='.pdb': shutil.copy2(p,out); return out
    try:
        from biotite.structure.io.pdbx import CIFFile, get_structure
        from biotite.structure.io.pdb import PDBFile
        a=get_structure(CIFFile.read(p),model=1); f=PDBFile(); f.set_structure(a); f.write(out); return out
    except Exception as e: raise RuntimeError(f'CIF conversion requires biotite: {e}')

def propka(pdb, outdir, configured=None, ph_on=6.5, ph_off=7.4):
    exe=executable(configured,'propka3')
    if not exe: return {'method':'unavailable','ionizable':0,'switchable':0,'delta_charge':0.0}
    outdir=Path(outdir); outdir.mkdir(parents=True,exist_ok=True)
    local=outdir/Path(pdb).name
    if local.resolve()!=Path(pdb).resolve(): shutil.copy2(pdb,local)
    run([exe,local.name],cwd=outdir,timeout=600)
    pka=outdir/(Path(pdb).stem+'.pka')
    vals=[]
    if pka.exists():
        for line in pka.read_text(errors='ignore').splitlines():
            m=PKA.match(line)
            if m: vals.append((m.group(1),float(m.group(4))))
    def q(aa,p,ph): return -1/(1+10**(p-ph)) if aa in ACID else 1/(1+10**(ph-p))
    dq=sum(q(aa,p,ph_on)-q(aa,p,ph_off) for aa,p in vals)
    lo,hi=sorted((ph_on,ph_off))
    return {'method':'propka','ionizable':len(vals),'switchable':sum(lo<=p<=hi for _,p in vals),'delta_charge':dq}
